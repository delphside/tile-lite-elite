# Read from this section only. Scanning the whole body found `waits on #253` in
# #71's table of placements, which is #251's dependency and not #71's.
DEPENDENCIES = "Dependencies and related work"

_DECLARED = re.compile(
    r"\b(waits on|is needed by)\s+((?:#\d+(?:\s+R\d+)?(?:\s*(?:,|and|&)\s*)?)+)",
    re.I)


@dataclass(frozen=True)
class Missing:
    number: int
    phrase: str     # "waits on" | "is needed by"
    other: int


def declared(body: str) -> list[tuple[str, int]]:
    """Every `waits on #N` and `is needed by #N` in a body, header excluded."""
    out = []
    for m in _DECLARED.finditer(strip(body)):
        phrase = m.group(1).lower()
        for n in re.findall(r"#(\d+)", m.group(2)):
            out.append((phrase, int(n)))
    return out


def undeclared_links(board: Mapping[int, Issue]) -> list[Missing]:
    """Dependencies a project's body states that GitHub does not hold."""
    found = []
    for issue in sorted(board.values(), key=lambda i: i.number):
        if not isinstance(issue, Project) or issue.state != "OPEN":
            continue
        for phrase, other in declared(issue.section(DEPENDENCIES)):
            if other == issue.number:
                continue
            held = issue.raw.blocked_by if phrase == "waits on" else issue.raw.blocks
            if other not in held:
                found.append(Missing(issue.number, phrase, other))
    # One finding per pair, however many times the body repeats it.
    return sorted(set(found), key=lambda f: (f.number, f.other, f.phrase))


def render_findings(stale_found: Sequence[tuple[int, str]],
                    links: Sequence[Missing],
                    colour: bool = True) -> str:
    bold = (lambda s: f"\033[1m{s}\033[0m") if colour else (lambda s: s)
    dim = (lambda s: f"\033[2m{s}\033[0m") if colour else (lambda s: s)
    red = (lambda s: f"\033[31m{s}\033[0m") if colour else (lambda s: s)
    green = (lambda s: f"\033[32m{s}\033[0m") if colour else (lambda s: s)

    out = [f"{bold('CONTEXT')}  {dim('R10 — the generated header on each open project')}"]
    if not stale_found:
        out.append(f"  {green('ok')} {dim('every open project carries a current header')}")
    for number, why in stale_found:
        out.append(f"  {red('!!')} {bold(f'#{number}')} {dim(why + ' — scripts/board-context.py --write')}")

    out += ["", f"{bold('DEPENDENCIES')}  {dim('R11 — declared in the body, held by GitHub')}"]
    if not links:
        out.append(f"  {green('ok')} {dim('every waits on / is needed by is a GitHub link')}")
    for f in links:
        out.append(f"  {red('!!')} {bold(f'#{f.number}')} {f.phrase} #{f.other}  "
                   f"{dim('not a GitHub dependency')}")
    return "\n".join(out)

