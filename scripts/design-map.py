#!/usr/bin/env python3
"""design-map.py — draws the design map, docs/4.2.0, from docs/design-map/.

One Structurizr model; its views are generated, never drawn by hand.

**Derived, never edited.** `--check` exits 1 if docs/4.2.0 differs from what
would be generated, so it catches a model change that was not redrawn.

It runs the Structurizr CLI from its Docker image, pinned in `IMAGE`, and so
needs Docker. Each view becomes a section titled by its C4 type and its
description in views.dsl, in the order views.dsl lists them; lifecycles.md,
when it exists, is appended as it stands.

  ./scripts/design-map.py           write docs/4.2.0-design-map.md
  ./scripts/design-map.py --check   exit 1 if it is stale
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

IMAGE = "structurizr/structurizr:2026.09.19"
ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "design-map"
TARGET = ROOT / "docs" / "4.2.0-design-map.md"

VIEW = re.compile(r'^\s*(container|component)\s+\S+\s+"([^"]+)"\s+"([^"]+)"', re.M)

HEADER = """# 4.2.0 Design map

**Generated by `scripts/design-map.py` from [`design-map/`](design-map/). Do not edit.**

The application as it is on `main`, drawn from one model. To change a
diagram, change [`model.dsl`](design-map/model.dsl) and run the script. Each
element's `artefact` property in `model.dsl` names the file or crate that
implements it.
"""


def export(out: Path) -> None:
    subprocess.run(
        ["docker", "run", "--rm", "-u", f"{os.getuid()}:{os.getgid()}",
         "-v", f"{SOURCE}:/w:ro", "-v", f"{out}:/out", "-w", "/w", IMAGE,
         "export", "-w", "map.dsl", "-f", "mermaid", "-o", "/out"],
        check=True, stdout=subprocess.DEVNULL)


def render() -> str:
    views = VIEW.findall((SOURCE / "views.dsl").read_text())
    if not views:
        sys.exit("design-map: no container or component views in views.dsl")
    with tempfile.TemporaryDirectory() as tmp:
        export(Path(tmp))
        parts = [HEADER]
        for kind, key, description in views:
            diagram = (Path(tmp) / f"structurizr-{key}.mmd").read_text().strip()
            parts.append(f"## {kind.capitalize()} view: {description}\n\n"
                         f"```mermaid\n{diagram}\n```\n")
    lifecycles = SOURCE / "lifecycles.md"
    if lifecycles.exists():
        parts.append(lifecycles.read_text().strip() + "\n")
    return "\n".join(parts)


def main() -> int:
    check = "--check" in sys.argv[1:]
    text = render()
    if check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(f"design-map: {TARGET.relative_to(ROOT)} is STALE; "
                  "run ./scripts/design-map.py", file=sys.stderr)
            return 1
        print("design-map: current")
        return 0
    TARGET.write_text(text)
    print(f"design-map: wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
